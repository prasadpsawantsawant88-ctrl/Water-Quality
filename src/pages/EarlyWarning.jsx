import { useState } from "react";
import { useApp } from "../state.jsx";
import { Card, Field, Note, PageHeader, RiskBadge, Kpi } from "../components/ui.jsx";
import { LAKE_NAMES } from "../lib/data.js";
import { DEFAULT_THRESHOLDS, LEVELS, RISK_COLORS, CANDIDATE_NOTICE } from "../lib/risk.js";
import { pct } from "../lib/stats.js";

const TYPE_LABEL = {
  CRITICAL: "Critical candidate", HIGH: "High candidate", VERIFY: "Verify (stale data)",
  FIELD_SAMPLING: "Field sampling", ESCALATION: "Escalation",
  AHP_PRIORITY: "AHP priority (interpolated)", AHP_UNCERTAIN: "Interpolation uncertain", DISAGREE: "AHP vs bloom model",
};

export default function EarlyWarning() {
  const { alerts, settings, setSettings, goto, run } = useApp();
  const [lake, setLake] = useState("All");
  const [sev, setSev] = useState("All");
  const [status, setStatus] = useState("All");
  const [type, setType] = useState("All");
  const th = settings.thresholds;

  const setTh = (k, v) => {
    const next = { ...th, [k]: v };
    // keep thresholds ordered
    if (!(next.moderate < next.high && next.high < next.critical)) return;
    setSettings({ ...settings, thresholds: next });
  };

  const shown = alerts
    .filter((a) => (lake === "All" || a.lake === lake) && (sev === "All" || a.severity === sev) && (status === "All" || a.status === status) && (type === "All" || a.type === type))
    .sort((a, b) => b.priority - a.priority);
  const counts = (t) => alerts.filter((a) => a.type === t).length;

  return (
    <div>
      <PageHeader title="Early-Warning Center" subtitle="Alert candidates generated by rules applied to the model probabilities. Candidates need human review; none is an issued warning." />
      <Note tone="danger" title="Not official warnings.">{CANDIDATE_NOTICE} No regulatory agency has issued any alert shown here, and the data are simulated.</Note>

      <div className="mt-4 grid grid-cols-2 gap-3 lg:grid-cols-4">
        <Kpi label="Critical candidates" value={counts("CRITICAL")} accent={RISK_COLORS.Critical} />
        <Kpi label="High candidates" value={counts("HIGH")} accent={RISK_COLORS.High} />
        <Kpi label="Verify: stale data" value={counts("VERIFY")} accent={RISK_COLORS.Moderate} />
        <Kpi label="Field sampling" value={counts("FIELD_SAMPLING")} accent="#5aa9e6" />
        <Kpi label="Escalations" value={counts("ESCALATION")} accent="#a98bff" />
        <Kpi label="AHP priority (Kriging)" value={counts("AHP_PRIORITY")} accent="#ff5c6c" />
        <Kpi label="Interpolation uncertain" value={counts("AHP_UNCERTAIN")} accent="#a98bff" />
        <Kpi label="AHP vs bloom model" value={counts("DISAGREE")} accent="#f2c14e" />
      </div>

      <div className="mt-4 grid gap-4 xl:grid-cols-4">
        <Card className="xl:col-span-3" title={`Alert candidates (${shown.length})`} subtitle="Ranked by priority score: probability, increased when confidence is low">
          <div className="mb-3 flex flex-wrap gap-3">
            <Field label="Lake"><select className="select" value={lake} onChange={(e) => setLake(e.target.value)}><option>All</option>{LAKE_NAMES.map((l) => <option key={l}>{l}</option>)}</select></Field>
            <Field label="Severity"><select className="select" value={sev} onChange={(e) => setSev(e.target.value)}><option>All</option>{LEVELS.map((l) => <option key={l}>{l}</option>)}</select></Field>
            <Field label="Monitoring status"><select className="select" value={status} onChange={(e) => setStatus(e.target.value)}><option>All</option><option>Monitored</option><option>Unmonitored</option></select></Field>
            <Field label="Alert type"><select className="select" value={type} onChange={(e) => setType(e.target.value)}><option value="All">All</option>{Object.entries(TYPE_LABEL).map(([k, v]) => <option key={k} value={k}>{v}</option>)}</select></Field>
          </div>
          <div className="max-h-[560px] overflow-auto">
            <table className="w-full">
              <thead><tr><th className="th">Priority</th><th className="th">Location</th><th className="th">Type</th><th className="th">Severity</th><th className="th">Severity basis · P(bloom)</th><th className="th">Detail</th></tr></thead>
              <tbody>
                {shown.map((a) => (
                  <tr key={a.id} className="cursor-pointer align-top hover:bg-slate-50" onClick={() => goto("geo", a.locationId)}>
                    <td className="td font-semibold">{a.priority.toFixed(0)}</td>
                    <td className="td font-semibold">{a.locationId}<div className="text-[11px] font-normal text-slate-500">{a.name} · {a.lake} · {a.status}</div></td>
                    <td className="td text-xs">{TYPE_LABEL[a.type]}</td>
                    <td className="td"><RiskBadge level={a.severity} />{a.type.startsWith("AHP") || a.type === "DISAGREE" ? <div className="mt-0.5 text-[10px] text-slate-500">AHP band</div> : null}</td>
                    <td className="td">{a.p === null ? "n/a" : pct(a.p)}</td>
                    <td className="td max-w-md text-xs text-slate-700">{a.detail}<div className="mt-0.5 text-[10px] italic text-slate-400">Candidate, not an official warning</div></td>
                  </tr>
                ))}
                {shown.length === 0 && <tr><td className="td text-center text-slate-500" colSpan={6}>No alert candidates match these filters.</td></tr>}
              </tbody>
            </table>
          </div>
        </Card>

        <div className="space-y-4">
          <Card title="Risk thresholds" subtitle="Illustrative prototype settings, not regulatory limits. Editing them re-classifies everything.">
            <div className="space-y-3">
              {[["moderate", "Moderate from"], ["high", "High from"], ["critical", "Critical from"]].map(([k, l]) => (
                <Field key={k} label={`${l}: ${(th[k] * 100).toFixed(0)}%`}><input type="range" min="0.05" max="0.95" step="0.05" value={th[k]} onChange={(e) => setTh(k, +e.target.value)} className="w-full" /></Field>
              ))}
              <button className="btn btn-ghost w-full" onClick={() => setSettings({ ...settings, thresholds: DEFAULT_THRESHOLDS })}>Reset to 20 / 40 / 70</button>
            </div>
          </Card>
          <Card title="Alert rule settings">
            <div className="space-y-3">
              <Field label={`Stale observation after ${settings.staleDays} days`}><input type="range" min="7" max="60" step="1" value={settings.staleDays} onChange={(e) => setSettings({ ...settings, staleDays: +e.target.value })} className="w-full" /></Field>
              <Field label={`Escalation jump ≥ ${(settings.escalationDelta * 100).toFixed(0)} pts`}><input type="range" min="0.05" max="0.4" step="0.05" value={settings.escalationDelta} onChange={(e) => setSettings({ ...settings, escalationDelta: +e.target.value })} className="w-full" /></Field>
            </div>
            <ul className="mt-3 list-disc space-y-1 pl-4 text-[11px] leading-relaxed text-slate-600">
              <li>P ≥ critical → critical candidate; P ≥ high → high candidate.</li>
              <li>Monitored, P ≥ moderate and last sample older than the stale limit → verify.</li>
              <li>Unmonitored, P ≥ high and weak support (low confidence, fewer than 3 stations, or far nearest station) → targeted field sampling.</li>
              <li>Probability rise ≥ escalation jump, or two risk levels, since the previous run → escalation.</li>
              <li>No station close enough to estimate → field sampling.</li>
              <li>Unmonitored, Kriging + AHP: chance of reaching the AHP threshold ≥ 50% → priority sampling; wide interval or far stations → uncertainty alert.</li>
              <li>AHP band and bloom-model level two or more steps apart → verify in the field. The two are different quantities.</li>
            </ul>
          </Card>
        </div>
      </div>
    </div>
  );
}
